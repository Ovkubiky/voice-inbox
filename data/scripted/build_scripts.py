UA_WEEKDAYS = {"понеділ": 0, "вівтор": 1, "серед": 2, "четвер(?!т)": 3, "п'ятниц": 4, "субот": 5, "неділ": 6}


def check(note_id: str, ref: str, item: dict) -> None:
    """Sanity checks: weekday phrases land on the right weekday, dates are in the future."""
    if not item["start"]:
        return
    ref_d = datetime.fromisoformat(ref).date()
    d = date.fromisoformat(item["start"][:10])
    assert d >= ref_d, f"{note_id}: {d} before ref {ref_d}"
    phrase = (item["date_phrase"] or "").lower()
    for stem, wd in UA_WEEKDAYS.items():
        if re.search(rf"(?<![а-яіїєґ]){stem}", phrase):
            assert d.weekday() == wd, f"{note_id}: '{phrase}' -> {d} is weekday {d.weekday()}, expected {wd}"


def main() -> None:
    with OUT.open("w", encoding="utf-8") as fh:
        for note_id, ref, text, tags, items in NOTES:
            for item in items:
                check(note_id, ref, item)
            fh.write(json.dumps({"id": note_id, "ref_time": ref, "text": text, "tags": tags, "items": items},
                                ensure_ascii=False) + "\n")
    print(f"Wrote {len(NOTES)} notes -> {OUT}")


if __name__ == "__main__":
    main()
