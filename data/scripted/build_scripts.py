"""Builds data/scripted/scripts.jsonl: the gold evaluation set (63 scripted Ukrainian voice notes).

Gold datetimes are written explicitly, then sanity-checked against the labelling conventions below.

Labelling conventions (also the spec for C5 · Date Resolver):
  1. Bare weekday ("в четвер")             -> nearest occurrence strictly after the reference day.
  2. "наступн* <weekday>"                  -> that weekday in the NEXT calendar week (weeks start Monday).
  3. "наступного тижня"                    -> Monday of next week, date only.
  4. "до кінця тижня"                      -> Friday of the current week, date only.
  5. "до кінця місяця"                     -> last day of the month, date only.
  6. "до <weekday>" (deadline)             -> rule 1, date only.
  7. Clock hours 1–7 without "ранку"       -> PM; 8–11 -> AM; "пів на N" -> (N-1):30.
  8. зранку/вранці -> 09:00, в обід/до обіду -> 13:00, після обіду -> 14:00, ввечері -> 19:00.
  9. "через N днів/тижнів"                 -> +N days/weeks, date only; "через годину" -> ref + 1h.
 10. Events with no resolvable day, or items whose person is only a pronoun -> is_incomplete = true.

Run: uv run python data/scripted/build_scripts.py
"""

