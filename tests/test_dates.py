from datetime import datetime

import pytest

from inbox.dates import resolve_rules

MON = datetime(2026, 11, 9, 9, 0)
THU = datetime(2026, 11, 12, 8, 15)
SUN = datetime(2026, 11, 15, 20, 0)


@pytest.mark.parametrize("phrase,ref,expected", [
    ("в четвер о третій", MON, "2026-11-12T15:00"),
    ("в четвер", THU, "2026-11-19"),                       # strictly after today
    ("в наступну середу о десятій", THU, "2026-11-18T10:00"),
    ("завтра зранку", MON, "2026-11-10T09:00"),
    ("завтра о четвертій", datetime(2026, 11, 14, 11), "2026-11-15T16:00"),  # 'четвертій' is not Thursday
    ("у понеділок о дев'ятій ранку", datetime(2026, 11, 14, 11), "2026-11-16T09:00"),  # not Sunday
    ("в середу о пів на третю", SUN, "2026-11-18T14:30"),
    ("завтра о дев'ятій тридцять", SUN, "2026-11-16T09:30"),
    ("через годину", datetime(2026, 11, 16, 9, 30), "2026-11-16T10:30"),
    ("через два тижні", datetime(2026, 11, 13, 13), "2026-11-27"),
    ("до кінця тижня", datetime(2026, 11, 10, 10), "2026-11-13"),
    ("до кінця місяця", datetime(2026, 11, 25, 12), "2026-11-30"),
    ("п'ятнадцятого грудня", THU, "2026-12-15"),
    ("двадцять першого листопада о десятій", SUN, "2026-11-21T10:00"),
    ("третього грудня о шостій вечора", datetime(2026, 11, 11, 18, 30), "2026-12-03T18:00"),
    ("на одинадцяту завтра", MON, "2026-11-10T11:00"),
    ("наступного тижня", datetime(2026, 11, 13, 13), "2026-11-16"),
    ("сьогодні ввечері", datetime(2026, 11, 11, 18, 30), "2026-11-11T19:00"),
    ("до обіду", datetime(2026, 11, 16, 9, 30), "2026-11-16T13:00"),
])
def test_resolve_rules(phrase, ref, expected):
    assert resolve_rules(phrase, ref) == expected


def test_unresolvable_returns_none():
    assert resolve_rules("колись", MON) is None
